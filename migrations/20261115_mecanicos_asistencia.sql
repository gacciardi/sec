-- Agenda de mecanicos de asistencia, aislada por empresa. Ejecutar una vez en PostgreSQL.
BEGIN;
CREATE TABLE IF NOT EXISTS distribucion.mecanicos_asistencia (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 empresa_id uuid NOT NULL REFERENCES distribucion.empresas(id),
 nombre varchar(100) NOT NULL,
 telefono varchar(25) NOT NULL,
 activo boolean NOT NULL DEFAULT true,
 creado_en timestamptz NOT NULL DEFAULT now(),
 actualizado_en timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_mecanicos_asistencia_empresa ON distribucion.mecanicos_asistencia(empresa_id,activo,nombre);
COMMIT;
