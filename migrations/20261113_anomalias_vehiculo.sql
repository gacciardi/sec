-- Registro de anomalías de vehículos: migración aditiva.
BEGIN;
CREATE TABLE IF NOT EXISTS distribucion.anomalias_vehiculo (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 empresa_id uuid NOT NULL REFERENCES distribucion.empresas(id),
 conductor_id uuid NOT NULL REFERENCES distribucion.miembros(id),
 reparto_id uuid REFERENCES distribucion.repartos(id),
 camion_id uuid,
 tipo varchar(40) NOT NULL,
 descripcion text NOT NULL,
 prioridad varchar(20) NOT NULL DEFAULT 'NORMAL' CHECK (prioridad IN ('NORMAL','URGENTE')),
 estado varchar(20) NOT NULL DEFAULT 'PENDIENTE' CHECK (estado IN ('PENDIENTE','EN_REVISION','RESUELTA')),
 observacion_mantenimiento text NOT NULL DEFAULT '',
 latitud numeric(10,7),
 longitud numeric(10,7),
 creado_en timestamptz NOT NULL DEFAULT now(),
 actualizado_en timestamptz NOT NULL DEFAULT now(),
 resuelto_en timestamptz
);
CREATE INDEX IF NOT EXISTS idx_anomalias_vehiculo_pendientes ON distribucion.anomalias_vehiculo(empresa_id,estado,creado_en DESC);
COMMIT;
