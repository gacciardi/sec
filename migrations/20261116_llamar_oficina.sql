-- SEC Distribución: comunicación asociada a cliente/reparto. No altera las alertas de robo/mecánico.
BEGIN;
SET LOCAL lock_timeout = '5s';
SELECT pg_advisory_xact_lock(hashtext('sec_distribucion_llamar_oficina_v1'));
CREATE TABLE IF NOT EXISTS distribucion.oficina_respuestas (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 empresa_id uuid NOT NULL REFERENCES distribucion.empresas(id),
 codigo varchar(40) NOT NULL, nombre varchar(120) NOT NULL,
 activo boolean NOT NULL DEFAULT true,
 actualizado_en timestamptz NOT NULL DEFAULT now(),
 UNIQUE(empresa_id,codigo), UNIQUE(empresa_id,id)
);
CREATE TABLE IF NOT EXISTS distribucion.oficina_solicitudes (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 empresa_id uuid NOT NULL REFERENCES distribucion.empresas(id),
 conductor_id uuid NOT NULL, reparto_id uuid NOT NULL,
 codigo_cliente varchar(100) NOT NULL, nombre_cliente text NOT NULL,
 solicitud_clave uuid NOT NULL,
 motivo varchar(20) NOT NULL CHECK(motivo IN ('MERCADERIA','COBRANZA','OTRO')),
 observacion varchar(500) NOT NULL DEFAULT '',
 latitud numeric(10,7), longitud numeric(10,7),
 estado varchar(20) NOT NULL DEFAULT 'ENVIADA' CHECK(estado IN ('ENVIADA','CONFIRMADA','RESPONDIDA')),
 creada_en timestamptz NOT NULL DEFAULT now(),
 confirmada_en timestamptz, confirmada_por uuid,
 respuesta_id bigint, respuesta_nombre varchar(120), respuesta_observacion varchar(500),
 respondida_en timestamptz, respondida_por uuid, leida_conductor_en timestamptz,
 FOREIGN KEY(empresa_id,conductor_id) REFERENCES distribucion.miembros(empresa_id,id),
 FOREIGN KEY(empresa_id,reparto_id) REFERENCES distribucion.repartos(empresa_id,id),
 FOREIGN KEY(empresa_id,confirmada_por) REFERENCES distribucion.miembros(empresa_id,id),
 FOREIGN KEY(empresa_id,respondida_por) REFERENCES distribucion.miembros(empresa_id,id),
 FOREIGN KEY(empresa_id,respuesta_id) REFERENCES distribucion.oficina_respuestas(empresa_id,id),
 UNIQUE(empresa_id,conductor_id,solicitud_clave),
 CHECK((latitud IS NULL AND longitud IS NULL) OR (latitud IS NOT NULL AND longitud IS NOT NULL AND latitud BETWEEN -90 AND 90 AND longitud BETWEEN -180 AND 180)),
 CHECK(estado<>'RESPONDIDA' OR (respuesta_id IS NOT NULL AND respuesta_nombre IS NOT NULL AND respondida_por IS NOT NULL AND respondida_en IS NOT NULL))
);
CREATE UNIQUE INDEX IF NOT EXISTS idx_oficina_solicitud_abierta ON distribucion.oficina_solicitudes(empresa_id,conductor_id,reparto_id,codigo_cliente) WHERE estado IN ('ENVIADA','CONFIRMADA');
CREATE INDEX IF NOT EXISTS idx_oficina_solicitudes_empresa ON distribucion.oficina_solicitudes(empresa_id,estado,creada_en DESC);
CREATE INDEX IF NOT EXISTS idx_oficina_solicitudes_conductor ON distribucion.oficina_solicitudes(empresa_id,conductor_id,creada_en DESC);
INSERT INTO distribucion.oficina_respuestas(empresa_id,codigo,nombre)
SELECT e.id,v.codigo,v.nombre FROM distribucion.empresas e CROSS JOIN (VALUES ('ESPERAR','Esperar en el cliente'),('CONTINUAR','Seguir a otro cliente')) v(codigo,nombre)
ON CONFLICT(empresa_id,codigo) DO NOTHING;
COMMIT;
