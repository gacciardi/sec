-- SEC Distribución: Mantenimiento de Flota y Huella de Carbono.
-- Migración aditiva e idempotente. Incluye anomalías de vehículo aún no instaladas.
BEGIN;
CREATE TABLE IF NOT EXISTS distribucion.anomalias_vehiculo (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 empresa_id uuid NOT NULL REFERENCES distribucion.empresas(id),
 conductor_id uuid NOT NULL REFERENCES distribucion.miembros(id),
 reparto_id uuid REFERENCES distribucion.repartos(id),
 camion_id uuid,
 tipo varchar(40) NOT NULL,
 descripcion text NOT NULL,
 prioridad varchar(20) NOT NULL DEFAULT 'NORMAL' CHECK (prioridad IN ('NORMAL','URGENTE')),
 estado varchar(20) NOT NULL DEFAULT 'PENDIENTE' CHECK (estado IN ('PENDIENTE','EN_REVISION','RESUELTA')),
 observacion_mantenimiento text NOT NULL DEFAULT '',
 latitud numeric(10,7), longitud numeric(10,7),
 creado_en timestamptz NOT NULL DEFAULT now(), actualizado_en timestamptz NOT NULL DEFAULT now(),
 resuelto_en timestamptz
);
CREATE INDEX IF NOT EXISTS idx_anomalias_vehiculo_pendientes ON distribucion.anomalias_vehiculo(empresa_id,estado,creado_en DESC);

CREATE TABLE IF NOT EXISTS distribucion.mantenimiento_trabajos (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 empresa_id uuid NOT NULL REFERENCES distribucion.empresas(id),
 vehiculo_id uuid NOT NULL REFERENCES distribucion.vehiculos(id),
 anomalia_id bigint REFERENCES distribucion.anomalias_vehiculo(id),
 fecha date NOT NULL,
 tipo varchar(20) NOT NULL CHECK (tipo IN ('PREVENTIVO','CORRECTIVO')),
 sistema varchar(60) NOT NULL,
 falla text NOT NULL DEFAULT '',
 trabajo_realizado text NOT NULL,
 repuestos text NOT NULL DEFAULT '',
 taller varchar(150) NOT NULL DEFAULT '',
 kilometraje numeric(12,1) CHECK (kilometraje>=0),
 costo numeric(16,2) NOT NULL DEFAULT 0 CHECK (costo>=0),
 proximo_servicio_fecha date,
 proximo_servicio_km numeric(12,1) CHECK (proximo_servicio_km>=0),
 registrado_por uuid REFERENCES distribucion.miembros(id),
 registrado_en timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_mantenimiento_trabajos_vehiculo ON distribucion.mantenimiento_trabajos(empresa_id,vehiculo_id,fecha DESC);

CREATE TABLE IF NOT EXISTS distribucion.combustible_cargas (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 empresa_id uuid NOT NULL REFERENCES distribucion.empresas(id),
 vehiculo_id uuid NOT NULL REFERENCES distribucion.vehiculos(id),
 fecha date NOT NULL,
 litros numeric(14,3) NOT NULL CHECK (litros>0),
 kilometros_periodo numeric(14,2) CHECK (kilometros_periodo>0),
 odometro numeric(14,1) CHECK (odometro>=0),
 costo numeric(16,2) CHECK (costo>=0),
 observacion text NOT NULL DEFAULT '',
 registrado_por uuid REFERENCES distribucion.miembros(id),
 registrado_en timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_combustible_cargas_vehiculo ON distribucion.combustible_cargas(empresa_id,vehiculo_id,fecha DESC);
COMMIT;
