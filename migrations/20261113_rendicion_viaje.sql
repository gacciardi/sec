-- Migración aditiva. Ejecutar sobre PostgreSQL después de revisar respaldo.
-- No modifica pedidos, visitas ni rendiciones históricas.
BEGIN;
CREATE SCHEMA IF NOT EXISTS distribucion;

CREATE TABLE IF NOT EXISTS distribucion.motivos_rechazo (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 empresa_id uuid NOT NULL REFERENCES distribucion.empresas(id),
 codigo varchar(30) NOT NULL,
 nombre varchar(150) NOT NULL,
 area_responsable varchar(30) NOT NULL DEFAULT 'OTROS'
  CHECK (area_responsable IN ('COMERCIAL','DISTRIBUCION','CLIENTE','OTROS')),
 activo boolean NOT NULL DEFAULT true,
 orden integer NOT NULL DEFAULT 100,
 creado_en timestamptz NOT NULL DEFAULT now(),
 actualizado_en timestamptz NOT NULL DEFAULT now(),
 UNIQUE (empresa_id,codigo)
);

CREATE TABLE IF NOT EXISTS distribucion.medios_cobranza (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 empresa_id uuid NOT NULL REFERENCES distribucion.empresas(id),
 codigo varchar(30) NOT NULL,
 nombre varchar(150) NOT NULL,
 clasificacion varchar(30) NOT NULL DEFAULT 'OTRO'
  CHECK (clasificacion IN ('EFECTIVO','DIGITAL','CHEQUE','OTRO')),
 activo boolean NOT NULL DEFAULT true,
 orden integer NOT NULL DEFAULT 100,
 creado_en timestamptz NOT NULL DEFAULT now(),
 actualizado_en timestamptz NOT NULL DEFAULT now(),
 UNIQUE (empresa_id,codigo)
);

-- Un registro por cliente y reparto; puede representar varios pedidos.
CREATE TABLE IF NOT EXISTS distribucion.rendicion_entregas (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 empresa_id uuid NOT NULL REFERENCES distribucion.empresas(id),
 reparto_id uuid NOT NULL REFERENCES distribucion.repartos(id),
 codigo_cliente varchar(100) NOT NULL,
 estado varchar(20) NOT NULL CHECK (estado IN ('ENTREGADO','PARCIAL','RECHAZADO')),
 motivo_rechazo_id bigint REFERENCES distribucion.motivos_rechazo(id),
 motivo_rechazo_nombre varchar(150),
 importe_original numeric(16,2) NOT NULL CHECK (importe_original>=0),
 importe_entregado numeric(16,2) NOT NULL CHECK (importe_entregado>=0),
 importe_rechazado numeric(16,2) GENERATED ALWAYS AS (importe_original-importe_entregado) STORED,
 observacion text,
 actualizado_por uuid REFERENCES distribucion.miembros(id),
 actualizado_en timestamptz NOT NULL DEFAULT now(),
 UNIQUE (empresa_id,reparto_id,codigo_cliente),
 CHECK (importe_entregado<=importe_original),
 CHECK (estado<>'ENTREGADO' OR importe_entregado=importe_original),
 CHECK (estado<>'RECHAZADO' OR (importe_entregado=0 AND motivo_rechazo_id IS NOT NULL)),
 CHECK (estado<>'PARCIAL' OR (importe_entregado>0 AND importe_entregado<importe_original))
);

-- Varios medios por entrega: permite pagos mixtos.
CREATE TABLE IF NOT EXISTS distribucion.rendicion_cobros (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 empresa_id uuid NOT NULL REFERENCES distribucion.empresas(id),
 rendicion_entrega_id bigint NOT NULL REFERENCES distribucion.rendicion_entregas(id),
 medio_cobranza_id bigint NOT NULL REFERENCES distribucion.medios_cobranza(id),
 medio_nombre varchar(150) NOT NULL,
 medio_clasificacion varchar(30) NOT NULL CHECK (medio_clasificacion IN ('EFECTIVO','DIGITAL','CHEQUE','OTRO')),
 importe numeric(16,2) NOT NULL CHECK (importe>0),
 referencia varchar(150),
 registrado_por uuid REFERENCES distribucion.miembros(id),
 registrado_en timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_rendicion_entregas_reparto ON distribucion.rendicion_entregas(empresa_id,reparto_id);
CREATE INDEX IF NOT EXISTS idx_rendicion_entregas_motivo ON distribucion.rendicion_entregas(empresa_id,motivo_rechazo_id);
CREATE INDEX IF NOT EXISTS idx_rendicion_cobros_entrega ON distribucion.rendicion_cobros(empresa_id,rendicion_entrega_id);

-- Carga inicial idempotente por empresa. Nunca sobrescribe modificaciones posteriores.
INSERT INTO distribucion.motivos_rechazo(empresa_id,codigo,nombre,area_responsable,orden)
SELECT e.id,v.codigo,v.nombre,v.area,v.orden
FROM distribucion.empresas e
CROSS JOIN (VALUES
 ('SIN_DINERO','Sin dinero','CLIENTE',10),
 ('CERRADO','Comercio cerrado','CLIENTE',20),
 ('FUERA_HORARIO','Fuera de horario','DISTRIBUCION',30),
 ('NO_SOLICITADO','Pedido no solicitado','COMERCIAL',40),
 ('PEDIDO_INCORRECTO','Pedido incorrecto','COMERCIAL',50),
 ('MERCADERIA_DANADA','Mercadería dañada','OTROS',60),
 ('OTRO','Otro','OTROS',90)
) AS v(codigo,nombre,area,orden)
ON CONFLICT (empresa_id,codigo) DO NOTHING;

INSERT INTO distribucion.medios_cobranza(empresa_id,codigo,nombre,clasificacion,orden)
SELECT e.id,v.codigo,v.nombre,v.clasificacion,v.orden
FROM distribucion.empresas e
CROSS JOIN (VALUES
 ('EFECTIVO','Efectivo','EFECTIVO',10),
 ('QR_MERCADO_PAGO','QR Mercado Pago','DIGITAL',20),
 ('CHEQUE','Cheque','CHEQUE',30),
 ('OTRO','Otro','OTRO',90)
) AS v(codigo,nombre,clasificacion,orden)
ON CONFLICT (empresa_id,codigo) DO NOTHING;
COMMIT;
