-- SEC Distribución: cierre de caja por conductor y fecha. Aditiva; no modifica pedidos ni cobros.
BEGIN;
CREATE TABLE IF NOT EXISTS distribucion.cierres_caja_conductor (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 empresa_id uuid NOT NULL REFERENCES distribucion.empresas(id),
 conductor_id uuid NOT NULL REFERENCES distribucion.miembros(id),
 fecha date NOT NULL,
 efectivo_sistema numeric(16,2) NOT NULL CHECK (efectivo_sistema>=0),
 efectivo_declarado numeric(16,2) NOT NULL CHECK (efectivo_declarado>=0),
 diferencia numeric(16,2) NOT NULL,
 observacion text NOT NULL DEFAULT '',
 cerrado_en timestamptz NOT NULL DEFAULT now(),
 UNIQUE (empresa_id,conductor_id,fecha)
);
CREATE INDEX IF NOT EXISTS idx_cierre_caja_empresa_fecha ON distribucion.cierres_caja_conductor(empresa_id,fecha);
COMMIT;
