-- SEC Distribución: alertas del conductor, migración aditiva
BEGIN;
CREATE TABLE IF NOT EXISTS distribucion.alertas_conductor (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 empresa_id uuid NOT NULL REFERENCES distribucion.empresas(id),
 conductor_id uuid NOT NULL REFERENCES distribucion.miembros(id),
 reparto_id uuid REFERENCES distribucion.repartos(id),
 tipo varchar(20) NOT NULL CHECK(tipo IN ('ROBO','MECANICO')),
 es_prueba boolean NOT NULL DEFAULT false,
 estado varchar(20) NOT NULL DEFAULT 'ENVIADA' CHECK(estado IN ('ENVIADA','CONFIRMADA','RESUELTA')),
 latitud numeric(10,7),
 longitud numeric(10,7),
 observacion varchar(500),
 creada_en timestamptz NOT NULL DEFAULT now(),
 confirmada_en timestamptz,
 confirmada_por uuid REFERENCES distribucion.miembros(id),
 resuelta_en timestamptz,
 resuelta_por uuid REFERENCES distribucion.miembros(id)
);
CREATE INDEX IF NOT EXISTS idx_alertas_conductor_empresa_estado ON distribucion.alertas_conductor(empresa_id,estado,creada_en DESC);
CREATE INDEX IF NOT EXISTS idx_alertas_conductor_conductor ON distribucion.alertas_conductor(empresa_id,conductor_id,creada_en DESC);
COMMIT;
